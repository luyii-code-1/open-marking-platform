import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
import ts from 'typescript'

const source=await readFile(new URL('../src/richTextFormat.ts',import.meta.url),'utf8')
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText
const {paperFont,hexColor,pointLength,enclosedText,enclosedTextError,paragraphIndent,EditorHistory}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'))
for(const name of ['OMP Sans','Arial','Microsoft YaHei','微软雅黑','黑体','Calibri'])assert.equal(paperFont(name),'OMP Sans')
for(const name of ['OMP Serif','Times New Roman','宋体','仿宋'])assert.equal(paperFont(name),'OMP Serif')
assert.equal(paperFont('Uninstalled custom font'),'')
assert.equal(hexColor('#abc'),'#AABBCC')
assert.equal(hexColor('rgb(255, 0, 24)'),'#FF0018')
assert.equal(hexColor('rgba(1, 2, 3, 1)'),'#010203')
for(const value of ['url(https://example.com)','rgba(0, 0, 0, .5)','expression(alert(1))','rgb(256,0,0)','transparent'])assert.equal(hexColor(value),'')
assert.equal(pointLength('16px',6,36),'12pt')
assert.equal(pointLength('12pt',6,36),'12pt')
assert.equal(pointLength('25.4mm',0,144),'72pt')
assert.equal(pointLength('-18pt',-72,144),'-18pt')
for(const value of ['9999pt','-1pt','calc(4pt + 8pt)','url(x)'])assert.equal(pointLength(value,6,36),'')
assert.equal(enclosedText(' 答\u0000案\n '),'答案')
assert.equal(enclosedTextError('一二三四五六七八'),'')
assert.match(enclosedTextError('一二三四五六七八九'),/8/)
assert.equal(enclosedTextError('😀😀😀😀😀😀😀😀'),'')
assert.equal(paragraphIndent(0,-18),18)
assert.equal(paragraphIndent(24,-18),24)
const history=new EditorHistory()
history.reset('initial')
history.record('typed once','typing',100)
history.record('typed twice','typing',300)
assert.equal(history.undo(),'initial')
assert.equal(history.redo(),'typed twice')
history.record('bold','command',400)
assert.equal(history.undo(),'typed twice')
history.record('different branch','command',500)
assert.equal(history.redo(),null)
history.breakGroup();history.record('next typing','typing',600)
assert.equal(history.undo(),'different branch')
console.log('Rich text formatting passed: embedded font mapping, safe colors/units, enclosed text and undo/redo branching')
