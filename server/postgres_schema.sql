-- Ensure primary keys remain immutable after creation.
CREATE FUNCTION omp_immutable_identifier() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.id<>NEW.id THEN RAISE EXCEPTION 'identifier immutable' USING ERRCODE='23514'; END IF;
    IF TG_TABLE_NAME='objects' THEN
        IF OLD.kind<>NEW.kind OR (OLD.deleted<>0 AND NEW.deleted=0) THEN
            RAISE EXCEPTION 'identifier immutable' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER object_identifier_update BEFORE UPDATE OF id,kind,deleted ON objects FOR EACH ROW EXECUTE FUNCTION omp_immutable_identifier();
CREATE TRIGGER user_identifier_update BEFORE UPDATE OF id ON users FOR EACH ROW EXECUTE FUNCTION omp_immutable_identifier();

CREATE FUNCTION omp_check_candidate_number() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE number text := NEW.body::jsonb #>> '{candidate_number}';
BEGIN
    IF number IS NULL THEN RETURN NEW; END IF;
    IF TG_OP='UPDATE' AND OLD.deleted=0 AND (OLD.body::jsonb #>> '{candidate_number}') IS NOT DISTINCT FROM number THEN
        RETURN NEW;
    END IF;
    -- Existing databases can contain duplicate numbers. Keep those identities
    -- editable while serializing every new assignment of the same number.
    PERFORM pg_advisory_xact_lock(hashtextextended('omp-candidate:' || current_schema() || ':' || number, 0));
    IF EXISTS (SELECT 1 FROM objects WHERE kind='students' AND deleted=0 AND id<>NEW.id AND body::jsonb #>> '{candidate_number}'=number) THEN
        RAISE EXCEPTION 'duplicate student candidate number' USING ERRCODE='23505';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER student_candidate_insert BEFORE INSERT ON objects FOR EACH ROW WHEN (NEW.kind='students' AND NEW.deleted=0) EXECUTE FUNCTION omp_check_candidate_number();
CREATE TRIGGER student_candidate_update BEFORE UPDATE OF body,deleted ON objects FOR EACH ROW WHEN (NEW.kind='students' AND NEW.deleted=0) EXECUTE FUNCTION omp_check_candidate_number();

CREATE FUNCTION omp_mark_scanned_group() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE scanned text;
BEGIN
    IF NEW.kind='submissions' THEN
        scanned:=NEW.body::jsonb #>> '{group_id}';
    ELSE
        SELECT body::jsonb #>> '{group_id}' INTO scanned FROM objects WHERE kind='scan-batches' AND id=NEW.body::jsonb #>> '{batch_id}';
    END IF;
    IF scanned IS NOT NULL THEN INSERT INTO scanned_groups VALUES(scanned) ON CONFLICT DO NOTHING; END IF;
    RETURN NULL;
END $$;
CREATE TRIGGER mark_scanned_submission AFTER INSERT ON objects FOR EACH ROW WHEN (NEW.kind='submissions') EXECUTE FUNCTION omp_mark_scanned_group();
CREATE TRIGGER mark_scanned_page AFTER INSERT ON objects FOR EACH ROW WHEN (NEW.kind='pages') EXECUTE FUNCTION omp_mark_scanned_group();

CREATE FUNCTION omp_invalidate_allocations() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE old_template text; new_template text;
BEGIN
    IF TG_OP<>'INSERT' AND OLD.deleted=0 AND OLD.body::jsonb #>> '{status}'='ready' THEN
        old_template:=OLD.body::jsonb #>> '{template_id}';
    END IF;
    IF TG_OP<>'DELETE' AND NEW.deleted=0 AND NEW.body::jsonb #>> '{status}'='ready' THEN
        new_template:=NEW.body::jsonb #>> '{template_id}';
    END IF;
    IF old_template IS NOT DISTINCT FROM new_template THEN RETURN NULL; END IF;
    DELETE FROM allocation_state WHERE question_id IN (
        SELECT question->>'id' FROM objects t CROSS JOIN LATERAL jsonb_array_elements(t.body::jsonb->'questions') AS question
        WHERE t.id IN (old_template,new_template)
    );
    RETURN NULL;
END $$;
CREATE TRIGGER allocation_ready_insert AFTER INSERT ON objects FOR EACH ROW WHEN (NEW.kind='submissions') EXECUTE FUNCTION omp_invalidate_allocations();
CREATE TRIGGER allocation_ready_delete AFTER DELETE ON objects FOR EACH ROW WHEN (OLD.kind='submissions') EXECUTE FUNCTION omp_invalidate_allocations();
CREATE TRIGGER allocation_ready_update AFTER UPDATE OF body,deleted ON objects FOR EACH ROW WHEN (NEW.kind='submissions') EXECUTE FUNCTION omp_invalidate_allocations();

